class QuestionOut(BaseModel):
    """A question as served to the frontend.

    This is a single-user study tool, so the correct answer and notes ship with
    the question; the frontend reveals them only when the card is flipped.
    """

    id: str
    set_id: str
    type: QuestionType
    topic: str
    prompt: str
    options: list[str] | None
    correct_index: int | None
    answer_notes: str
    difficulty_rationale: str
    tags: QuestionTags


class QuestionSetSummary(BaseModel):
    id: str
    title: str
    track: str
    level: int
    description: str | None
    question_count: int


class SessionStartRequest(BaseModel):
    track: str
    level: int | None = Field(default=None, ge=1, le=5)
    mode: str = Field(default="level", pattern=r"^(level|typical-drill|custom)$")
    typicality: list[TypicalityTag] | None = None  # filter, e.g. drill only staples
    limit: int = Field(default=20, ge=1, le=100)


class SessionOut(BaseModel):
    id: str
    track: str
    level: int | None
    mode: str
    questions: list[QuestionOut]


class AnswerRequest(BaseModel):
    session_id: str
    question_id: str
    chosen_index: int | None = None  # for mc
    self_rating: SelfRating | None = None  # for flashcard

    @model_validator(mode="after")
    def check_exactly_one_answer_kind(self) -> "AnswerRequest":
        if (self.chosen_index is None) == (self.self_rating is None):
            raise ValueError("provide exactly one of chosen_index or self_rating")
        return self


class AnswerResult(BaseModel):
    question_id: str
    score: float
    correct: bool  # score >= 1.0
    correct_index: int | None
    answer_notes: str


class LevelProgress(BaseModel):
    level: int
    difficulty: DifficultyTag
    total_questions: int
    attempted_questions: int
    accuracy: float | None  # None until something was attempted
    unlocked: bool
    passed: bool  # accuracy >= threshold with sufficient coverage


class TrackProgress(BaseModel):
    track: str
    levels: list[LevelProgress]
    highest_unlocked: int


class TopicStat(BaseModel):
    topic: str
    attempts: int
    accuracy: float


class ExportSummary(BaseModel):
    """Performance export consumed by the quiz-forge skill."""

    generated_at: datetime
    total_answers: int
    tracks: list[TrackProgress]
    weak_topics: list[TopicStat]  # lowest accuracy first
    strong_topics: list[TopicStat]  # highest accuracy first
